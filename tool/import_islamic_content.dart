// Usage: dart run tool/import_islamic_content.dart
// Fetches fitrahive/dua-dhikr (MIT) and writes the generated migration.
import 'dart:convert';
import 'dart:io';

import 'package:http/http.dart' as http;

import 'content_import.dart';

const _base = 'https://raw.githubusercontent.com/fitrahive/dua-dhikr/main';
const _sets = [
  'daily-dua', 'selected-dua', 'morning-dhikr', 'evening-dhikr',
  'dhikr-after-salah',
];

Future<void> main() async {
  final tags = jsonDecode(File('tool/content_tags.json').readAsStringSync())
      as Map<String, dynamic>;
  final rows = <ImportRow>[];
  final counts = <String>[];
  for (final set in _sets) {
    final res = await http.get(Uri.parse('$_base/data/dua-dhikr/$set/en.json'));
    if (res.statusCode != 200) {
      throw StateError('fetch $set failed: ${res.statusCode}');
    }
    final items = (jsonDecode(utf8.decode(res.bodyBytes)) as List).cast<Map<String, dynamic>>();
    final r = rowsForSet(set, items, tags);
    rows.addAll(r);
    final approved = r.where((x) => x.status == 'approved').length;
    counts.add('$set: ${r.length} (approved $approved, pending ${r.length - approved})');
  }
  final c = await http.get(Uri.parse('https://api.github.com/repos/fitrahive/dua-dhikr/commits/main'));
  final sha = c.statusCode == 200 ? (jsonDecode(c.body)['sha'] as String).substring(0, 7) : null;
  final d = DateTime.now();
  final date = '${d.year}-${d.month.toString().padLeft(2, '0')}-${d.day.toString().padLeft(2, '0')}';
  final header = '-- GENERATED by tool/import_islamic_content.dart; do not edit by hand.\n'
      '-- Source: https://github.com/fitrahive/dua-dhikr (MIT, Copyright (c) 2023 Fitrahive)\n'
      '-- Imported: $date${sha == null ? '' : ' (upstream commit $sha)'}\n'
      '-- License text: assets/licenses/fitrahive-dua-dhikr.txt\n\n';
  File('supabase/migrations/20261116000005_islamic_content.sql')
      .writeAsStringSync(header + toSqlUpsert(rows));
  counts.forEach(stdout.writeln);
  stdout.writeln('total: ${rows.length}');
}
